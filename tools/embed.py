# Embed binary files as C arrays: embed.py out.h name=path [name=path ...]
import sys
with open(sys.argv[1], 'w') as f:
    f.write('// Generated by tools/embed.py — do not edit.\n#pragma once\n#include <cstddef>\n#include <cstdint>\n\n')
    for arg in sys.argv[2:]:
        name, path = arg.split('=', 1)
        data = open(path, 'rb').read()
        f.write('static const uint8_t %s[%d] = {\n' % (name, len(data)))
        for i in range(0, len(data), 24):
            f.write('    ' + ', '.join('0x%02X' % b for b in data[i:i + 24]) + ',\n')
        f.write('};\n\n')
