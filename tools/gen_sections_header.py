# Emit src/generated/iss_sections.h: every overlay code section (rom, vram, text size) from the symbol TOML.
import sys, re
syms = open(sys.argv[1]).read()
rows = []
for sec in syms.split('[[section]]')[1:]:
    name = re.search(r'name = "(\w+)"', sec).group(1)
    if name == 'main':
        continue
    rom, vram, size = (int(re.search(r'%s = (0x\w+)\n' % k, sec).group(1), 16) for k in ('rom', 'vram', 'size'))
    rows.append((rom, vram, size, name))
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/gen_sections_header.py — do not edit.\n#pragma once\n#include <cstdint>\n\n')
    f.write('struct IssCodeSection { uint32_t rom; uint32_t vram; uint32_t text_size; const char* name; };\n\n')
    f.write('static const IssCodeSection iss_code_sections[] = {\n')
    for rom, vram, size, name in sorted(rows):
        f.write('    { 0x%06X, 0x%08X, 0x%05X, "%s" },\n' % (rom, vram, size, name))
    f.write('};\n')
print(len(rows), 'overlay code sections')
